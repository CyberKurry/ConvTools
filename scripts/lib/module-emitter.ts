import type { ToolModuleManifest } from '../../core/module-sdk/manifest';
import { compareCodePoints } from '../../core/config/ordering';
import type { ScannedModule } from './types';

const HEADER = '// Generated by scripts/generate-modules.ts. Do not edit.\n';

export function emitRegistry(modules: readonly ScannedModule[]): string {
  const ordered = [...modules].sort((a, b) => compareCodePoints(a.manifest.id, b.manifest.id));
  const lines = ordered.map(
    (module) => `  '${module.manifest.id}': () => import('../modules/${module.manifest.id}/index'),`,
  );
  const body = lines.length > 0 ? `\n${lines.join('\n')}\n` : '\n';
  return `${HEADER}
export const moduleLoaders = {${body}} as const;
`;
}

export function emitManifest(modules: readonly ScannedModule[]): string {
  const ordered = [...modules].sort((a, b) => compareCodePoints(a.manifest.id, b.manifest.id));
  const optionalPermissions = uniqueSorted(
    ordered.flatMap((module) => module.manifest.permissions.optionalPermissions),
  );
  const optionalHostPermissions = uniqueSorted(
    ordered.flatMap((module) => module.manifest.permissions.optionalHostPermissions),
  );
  const bodies = ordered.map((module) => emitOne(module.manifest)).join(',\n');
  const body = bodies.length > 0 ? `\n${bodies}\n` : '\n';
  const names = ordered.map((module) => `  ${quote(module.manifest.id)}: { en: ${quote(module.enName)}, zh_CN: ${quote(module.zhName)} },`).join('\n');
  const nameBody = names.length > 0 ? `\n${names}\n` : '\n';
  const labels = ordered
    .map((module) => {
      const actions = Object.entries(module.selectionActionLabels)
        .sort(([a], [b]) => compareCodePoints(a, b))
        .map(([actionId, label]) => `    ${quote(actionId)}: { en: ${quote(label.en)}, zh_CN: ${quote(label.zh_CN)} },`)
        .join('\n');
      return `  ${quote(module.manifest.id)}: {\n${actions}\n  },`;
    })
    .join('\n');
  const labelBody = labels.length > 0 ? `\n${labels}\n` : '\n';
  const icons = ordered.map((module) => `  ${quote(module.manifest.id)}: ${quote(module.iconSvg)},`).join('\n');
  const iconBody = icons.length > 0 ? `\n${icons}\n` : '\n';
  const locales = ordered
    .map(
      (module) =>
        `  ${quote(module.manifest.id)}: { en: ${emitJson(module.enLocale)}, zh_CN: ${emitJson(module.zhLocale)} },`,
    )
    .join('\n');
  const localeBody = locales.length > 0 ? `\n${locales}\n` : '\n';
  return `${HEADER}import type { ToolModuleManifest } from '../core/module-sdk/manifest';

export const moduleManifests = [${body}] as const satisfies readonly ToolModuleManifest[];

export const moduleDisplayNames = {${nameBody}} as const;

export const moduleSelectionActionLabels = {${labelBody}} as const;

export const moduleIconSvg = {${iconBody}} as const;

export const moduleLocales = {${localeBody}} as const;

export const optionalPermissions = [${optionalPermissions.map(quote).join(', ')}] as const;
export const optionalHostPermissions = [${optionalHostPermissions.map(quote).join(', ')}] as const;
`;
}

function emitOne(manifest: ToolModuleManifest): string {
  const actions = manifest.surfaces.selectionActions.map(quote).join(', ');
  const optionalPermissions = manifest.permissions.optionalPermissions.map(quote).join(', ');
  const optionalHostPermissions = manifest.permissions.optionalHostPermissions.map(quote).join(', ');
  const quick =
    manifest.defaultQuickOrder === null ? 'null' : String(manifest.defaultQuickOrder);
  return `  {
    id: ${quote(manifest.id)},
    version: ${quote(manifest.version)},
    coreApiRange: ${quote(manifest.coreApiRange)},
    icon: ${quote(manifest.icon)},
    defaultEnabled: ${String(manifest.defaultEnabled)},
    defaultQuickOrder: ${quick},
    surfaces: {
      popup: ${String(manifest.surfaces.popup)},
      workbench: ${String(manifest.surfaces.workbench)},
      settings: ${String(manifest.surfaces.settings)},
      selectionActions: [${actions}],
    },
    permissions: {
      optionalPermissions: [${optionalPermissions}],
      optionalHostPermissions: [${optionalHostPermissions}],
    },
  }`;
}

function uniqueSorted(values: readonly string[]): string[] {
  return [...new Set(values)].sort(compareCodePoints);
}

function emitJson(value: Record<string, unknown>): string {
  const sorted = Object.fromEntries(Object.entries(value).sort(([a], [b]) => compareCodePoints(a, b)));
  return JSON.stringify(sorted, null, 2).replaceAll('\n', '\n  ');
}

function quote(value: string): string {
  return `'${value
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t')}'`;
}
